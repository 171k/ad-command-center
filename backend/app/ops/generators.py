def tcpdump_command(spec: dict) -> dict:
    """Build a bounded tcpdump capture command from inputs.

    spec: interface, ports(list[int]), protocol(tcp/udp/''), hosts(list[str]),
          exclude_ssh(bool), snaplen(int), rotate_seconds(int), rotate_mb(int),
          keep_files(int), out_dir(str), out_prefix(str)
    Returns {command, rotate_command, bpf, notes}.
    """
    iface = _safe_token(spec.get("interface") or "<iface>")
    snaplen = int(spec.get("snaplen") or 0)  # 0 = full packet
    rotate_seconds = int(spec.get("rotate_seconds") or 0)
    rotate_mb = int(spec.get("rotate_mb") or 0)
    keep_files = int(spec.get("keep_files") or 0)
    out_dir = (spec.get("out_dir") or "./captures").rstrip("/")
    prefix = _safe_token(spec.get("out_prefix") or "cap")

    bpf = _build_bpf(spec)
    parts = ["sudo", "tcpdump", "-i", iface, "-n", "-s", str(snaplen)]
    if rotate_seconds:
        parts += ["-G", str(rotate_seconds)]
    if rotate_mb:
        parts += ["-C", str(rotate_mb)]
    if keep_files:
        parts += ["-W", str(keep_files)]
    # Rotating output needs a strftime pattern in -w.
    outfile = f"{out_dir}/{prefix}-%Y%m%d-%H%M%S.pcap" if (rotate_seconds or rotate_mb) else f"{out_dir}/{prefix}.pcap"
    parts += ["-w", outfile]
    if bpf:
        parts += [bpf]  # quoted below
    cmd = _join_tcpdump(parts, bpf)

    # Rotate-and-upload variant (post-rotate hook curls each finished pcap).
    rotate_cmd = ""
    if rotate_seconds or rotate_mb:
        hook_parts = parts[:]
        # insert -z <script> before -w
        wi = hook_parts.index("-w")
        hook_parts[wi:wi] = ["-z", "./pcap_upload.sh"]
        rotate_cmd = _join_tcpdump(hook_parts, bpf)

    notes = [
        "Run on an authorised host / permitted capture interface only.",
        "Bounded: -W limits the number of rotated files so disk stays bounded.",
        "-s 0 captures full packets; lower snaplen if you only need headers.",
        "Inside a container, the host interface may not be visible; capture on "
        "the host or in the right network namespace (nsenter).",
        "Exclude SSH and your own upload traffic to avoid noise and loops.",
    ]
    return {"command": cmd, "rotate_command": rotate_cmd, "bpf": bpf, "notes": notes,
            "out_dir": out_dir}


def _build_bpf(spec: dict) -> str:
    clauses = []
    proto = (spec.get("protocol") or "").lower()
    if proto in ("tcp", "udp"):
        clauses.append(proto)
    ports = [int(p) for p in (spec.get("ports") or []) if str(p).strip().isdigit()]
    if ports:
        clauses.append("(" + " or ".join(f"port {p}" for p in ports) + ")")
    hosts = [h for h in (spec.get("hosts") or []) if _is_hostish(h)]
    if hosts:
        clauses.append("(" + " or ".join(f"host {h}" for h in hosts) + ")")
    if spec.get("exclude_ssh", True):
        clauses.append("not port 22")
    return " and ".join(clauses)


def _join_tcpdump(parts: list[str], bpf: str) -> str:
    out = []
    i = 0
    while i < len(parts):
        tok = parts[i]
        if tok == bpf and bpf:
            out.append(shlex.quote(bpf))
        else:
            out.append(tok)
        i += 1
    return " ".join(out)


def _safe_token(s: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_.:/\-]", "", str(s))[:64] or "x"


def _is_hostish(s: str) -> bool:
    return bool(re.fullmatch(r"[a-zA-Z0-9_.:\-]{1,253}", str(s or "")))
