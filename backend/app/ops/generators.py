"""Deterministic code/command generators. No AI, no execution, no network.

- rce_script(): turn a manually verified vulnerability into a reusable, editable
  Python testing script (http / tcp / requests / pwntools). The operator supplies
  the authorised target and payload; we only format readable, standalone code.
- tcpdump_command(): build a bounded tcpdump capture command (and a rotate-and-
  upload variant) from interface/filter/rotation inputs.

Generated scripts are meant to be reviewed and run on the operator's own box
(Kali), never executed by this server. Target authorisation is enforced by the
caller against the registered scope; these functions only format text.
"""
from __future__ import annotations

import json
import re
import shlex

PROTOCOLS = ("http", "tcp", "requests", "pwntools")

_BANNER = (
    "# Generated by A&D Command Center - RCE Script Generator.\n"
    "# AUTHORISED TARGETS ONLY. Review before running. Run from your own box\n"
    "# (e.g. Kali), not the Command Center server. This does not confirm RCE;\n"
    "# confirm with explicit execution evidence.\n"
)


def _py_str(s: str) -> str:
    """Safe Python string literal for arbitrary text."""
    return json.dumps(s if s is not None else "")


def _headers_block(headers: dict, indent: str = "    ") -> str:
    if not headers:
        return f"{indent}headers = {{}}\n"
    lines = [f"{indent}headers = {{"]
    for k, v in headers.items():
        lines.append(f"{indent}    {_py_str(str(k))}: {_py_str(str(v))},")
    lines.append(f"{indent}}}")
    return "\n".join(lines) + "\n"


def rce_script(spec: dict) -> dict:
    """Return {'filename', 'language', 'script'} for the given spec.

    spec keys (all optional except protocol/host):
      protocol: one of PROTOCOLS
      name, host, port, tls(bool), path, method(GET/POST)
      headers(dict), params(dict for query), body(str, may contain {{PAYLOAD}})
      payload(str), expected(str to match in response), timeout(int)
    """
    proto = (spec.get("protocol") or "requests").lower()
    if proto not in PROTOCOLS:
        raise ValueError(f"unknown protocol: {proto}")
    host = (spec.get("host") or "").strip()
    if not host:
        raise ValueError("host is required")
    port = int(spec.get("port") or (443 if spec.get("tls") else 80))
    tls = bool(spec.get("tls"))
    path = spec.get("path") or "/"
    method = (spec.get("method") or "GET").upper()
    headers = spec.get("headers") or {}
    params = spec.get("params") or {}
    body = spec.get("body") or ""
    payload = spec.get("payload") or ""
    expected = spec.get("expected") or ""
    timeout = int(spec.get("timeout") or 10)
    name = re.sub(r"[^a-zA-Z0-9_]+", "_", (spec.get("name") or "exploit")).strip("_") or "exploit"

    builders = {
        "requests": _requests_script,
        "http": _http_raw_script,
        "tcp": _tcp_script,
        "pwntools": _pwntools_script,
    }
    ctx = dict(host=host, port=port, tls=tls, path=path, method=method, headers=headers,
               params=params, body=body, payload=payload, expected=expected,
               timeout=timeout, name=name)
    script = builders[proto](ctx)
    return {"filename": f"{name}.py", "language": "python", "script": script}


def _expected_check(expected: str, var: str = "text") -> str:
    if not expected:
        return ("    # TODO: define a success indicator to confirm the finding\n"
                f"    ok = False  # e.g. {_py_str('flag{')} in {var}\n")
    return (f"    ok = {_py_str(expected)} in {var}\n"
            "    print('[+] SUCCESS: expected marker found' if ok else '[-] marker not found')\n")


def _requests_script(c: dict) -> str:
    scheme = "https" if c["tls"] else "http"
    base = f"{scheme}://{c['host']}:{c['port']}"
    hdr = _headers_block(c["headers"])
    params_lit = _py_str_dict(c["params"])
    body = c["body"]
    data_line = ""
    if c["method"] == "POST":
        if body:
            data_line = f"    data = {_py_str(body)}.replace('{{{{PAYLOAD}}}}', PAYLOAD)\n"
        else:
            data_line = "    data = PAYLOAD\n"
    call = (
        "        r = requests.post(url, headers=headers, params=params, data=data, "
        "timeout=TIMEOUT, verify=True)\n"
        if c["method"] == "POST" else
        "        r = requests.get(url, headers=headers, params=params, timeout=TIMEOUT, verify=True)\n"
    )
    return f'''{_BANNER}import sys
import requests

TARGET = {_py_str(base)}
PATH = {_py_str(c["path"])}
PAYLOAD = {_py_str(c["payload"])}   # operator-supplied; edit freely
TIMEOUT = {c["timeout"]}


def run():
    url = TARGET.rstrip("/") + PATH
{hdr}    params = {params_lit}
{data_line}    try:
{call}    except requests.RequestException as e:
        print("[!] request failed:", e)
        return 2
    print(f"[*] HTTP {{r.status_code}} ({{len(r.content)}} bytes)")
    text = r.text
{_expected_check(c["expected"])}    sys.stdout.write(text[:2000])
    return 0


if __name__ == "__main__":
    sys.exit(run())
'''


def _http_raw_script(c: dict) -> str:
    # Raw HTTP over a socket (optionally TLS). Useful when requests normalises too much.
    body = c["body"] or "{{PAYLOAD}}"
    hdr_lines = "".join(
        f'    req += {_py_str(f"{k}: {v}")} + CRLF\n' for k, v in (c["headers"] or {}).items()
    )
    tls_wrap = (
        "    import ssl\n"
        "    ctx = ssl.create_default_context()\n"
        "    sock = ctx.wrap_socket(socket.create_connection((HOST, PORT), TIMEOUT), server_hostname=HOST)\n"
        if c["tls"] else
        "    sock = socket.create_connection((HOST, PORT), TIMEOUT)\n"
    )
    return f'''{_BANNER}import socket
import sys

HOST = {_py_str(c["host"])}
PORT = {c["port"]}
PATH = {_py_str(c["path"])}
PAYLOAD = {_py_str(c["payload"])}
TIMEOUT = {c["timeout"]}
CRLF = "\\r\\n"


def run():
    data = {_py_str(body)}.replace("{{{{PAYLOAD}}}}", PAYLOAD)
    req = f"{c['method']} {{PATH}} HTTP/1.1" + CRLF
    req += f"Host: {{HOST}}" + CRLF
{hdr_lines}    req += "Connection: close" + CRLF
    if {("True" if c["method"] == "POST" else "False")}:
        req += f"Content-Length: {{len(data)}}" + CRLF + CRLF + data
    else:
        req += CRLF
{tls_wrap}    sock.sendall(req.encode())
    chunks = []
    try:
        while True:
            b = sock.recv(4096)
            if not b:
                break
            chunks.append(b)
    except socket.timeout:
        pass
    sock.close()
    resp = b"".join(chunks).decode("latin-1")
    text = resp
{_expected_check(c["expected"], "resp")}    sys.stdout.write(resp[:2000])
    return 0


if __name__ == "__main__":
    sys.exit(run())
'''


def _tcp_script(c: dict) -> str:
    return f'''{_BANNER}import socket
import sys

HOST = {_py_str(c["host"])}
PORT = {c["port"]}
PAYLOAD = {_py_str(c["payload"])}   # bytes to send; edit freely
TIMEOUT = {c["timeout"]}


def run():
    data = PAYLOAD.encode() if isinstance(PAYLOAD, str) else PAYLOAD
    sock = socket.create_connection((HOST, PORT), TIMEOUT)
    try:
        if data:
            sock.sendall(data)
        chunks = []
        while True:
            b = sock.recv(4096)
            if not b:
                break
            chunks.append(b)
    except socket.timeout:
        pass
    finally:
        sock.close()
    resp = b"".join(chunks).decode("latin-1")
    text = resp
{_expected_check(c["expected"], "resp")}    sys.stdout.write(resp[:2000])
    return 0


if __name__ == "__main__":
    sys.exit(run())
'''


def _pwntools_script(c: dict) -> str:
    return f'''{_BANNER}from pwn import *

HOST = {_py_str(c["host"])}
PORT = {c["port"]}
PAYLOAD = {_py_str(c["payload"])}   # edit freely

context.log_level = "info"


def run():
    io = remote(HOST, PORT, timeout={c["timeout"]})
    # io.recvuntil(b"> ")            # adjust to the service protocol
    io.sendline(PAYLOAD.encode() if isinstance(PAYLOAD, str) else PAYLOAD)
    data = io.recvall(timeout={c["timeout"]}).decode("latin-1", "replace")
    io.close()
    expected = {_py_str(c["expected"])}
    if expected and expected in data:
        log.success("expected marker found")
    print(data[:2000])


if __name__ == "__main__":
    run()
'''


def _py_str_dict(d: dict) -> str:
    if not d:
        return "{}"
    items = ", ".join(f"{_py_str(str(k))}: {_py_str(str(v))}" for k, v in d.items())
    return "{" + items + "}"


